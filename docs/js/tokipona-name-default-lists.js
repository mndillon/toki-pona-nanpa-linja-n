  function deepFreeze(obj) {
    if (!obj || typeof obj !== "object" || Object.isFrozen(obj)) return obj;
    Object.freeze(obj);
    for (const value of Object.values(obj)) deepFreeze(value);
    return obj;
  }

  function cloneLists() {
    return JSON.parse(JSON.stringify(TOKIPONA_NAME_DEFAULT_LISTS));
  }

  function flattenLists(options) {
    const opts = options || {};
    const includeGroups = Array.isArray(opts.groups) && opts.groups.length
      ? opts.groups
      : ["places", "boys", "girls"];
    const out = {};
    for (const group of includeGroups) {
      const src = TOKIPONA_NAME_DEFAULT_LISTS[group];
      if (!src || typeof src !== "object") continue;
      for (const [english, tokiponized] of Object.entries(src)) {
        if (!(english in out)) out[english] = tokiponized;
      }
    }
    return out;
  }

  function tokiponizedValues(options) {
    const opts = options || {};
    const maxLength = Number.isFinite(Number(opts.maxLength)) ? Number(opts.maxLength) : null;
    const seen = new Set();
    const out = [];
    for (const value of Object.values(flattenLists(opts))) {
      const name = String(value || "").trim();
      if (!name) continue;
      if (maxLength != null && name.length > maxLength) continue;
      const key = name.toLocaleLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      out.push(name);
    }
    return out;
  }

