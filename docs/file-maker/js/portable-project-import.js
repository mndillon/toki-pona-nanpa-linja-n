/* MIT — create an editable-source import plan from a verified Font Maker ZIP.
 * The parser does not mutate IndexedDB, open a font face or trust the ZIP's
 * licensing assertions as proof of legal permission. All payloads have first
 * passed the strict ZIP/CRC32/SHA-256 checks in portable-font-pair.js.
 */
import {readPortableFontPairZip} from './portable-font-pair.js';
import {safeDocName,MAX_DOC_BYTES} from './licensing.js';

const decoder=new TextDecoder('utf-8',{fatal:true});
const FAIRFAX_FILES=['LICENSES/Fairfax-SIL-OFL-1.1.txt','LICENSES/Fairfax-Copyright-Notice.txt'];
const LICENSE_MANIFEST='licence-manifest.json';
const INFO_FILE='FONT-INFORMATION.txt';

function jsonFile(files,path){
  const bytes=files.get(path);
  if(!bytes||bytes.length>256*1024)throw Error(`Font ZIP lacks a valid ${path}.`);
  try{return JSON.parse(decoder.decode(bytes));}
  catch{throw Error(`Font ZIP contains malformed ${path}.`);}
}
function equalNames(actual,declared,what){
  if(!Array.isArray(declared)||declared.length!==actual.length||
    declared.some((name,i)=>name!==actual[i]))throw Error(`Font ZIP ${what} declarations disagree with the verified file inventory.`);
}
function originalPathNames(docs){
  const used=new Set();
  return docs.map(doc=>{
    const clean=safeDocName(doc.originalName);
    let name=clean,n=2;
    while(used.has(name.toLowerCase()))name=`${n++}-${clean}`;
    used.add(name.toLowerCase());
    return `LICENSES/Original-${name}`;
  });
}
/**
 * Import an exported Ligatures/Literal font pair as the source for a NEW
 * editable project. Only original bundled licence files become source docs;
 * Fairfax's own files are regenerated by subsequent ordinary exports.
 * Old v1 ZIPs without the new explicit licensing descriptor are supported
 * when their signed-off licence-manifest v2 and original files agree.
 */
export async function readPortableFontProjectZip(file){
  const pair=await readPortableFontPairZip(file);
  const files=pair.verifiedFiles;
  const originalPaths=[...files.keys()].filter(name=>name.startsWith('LICENSES/Original-'));
  const fairfaxPaths=[...files.keys()].filter(name=>FAIRFAX_FILES.includes(name));
  const noticePaths=[...files.keys()].filter(name=>name===INFO_FILE);
  for(const path of [LICENSE_MANIFEST,INFO_FILE,...FAIRFAX_FILES]){
    if(!files.has(path)||files.get(path).length<1)throw Error(`Font ZIP is missing bundled licence/notice file ${path}; it cannot be imported without a separate licence.`);
  }
  const declaration=pair.manifest.licensing;
  if(declaration!=null){
    if(declaration.schema!=='spfm-portable-licensing-v1'||declaration.bundled!==true||declaration.manifestPath!==LICENSE_MANIFEST){
      throw Error('Font ZIP has an unsupported bundled-licensing manifest.');
    }
    equalNames(originalPaths,declaration.originalLicenceFiles,'original licence');
    equalNames(fairfaxPaths,declaration.fairfaxLicenceFiles,'Fairfax licence');
    equalNames(noticePaths,declaration.noticeFiles,'licence notice');
  }
  const licenceMeta=jsonFile(files,LICENSE_MANIFEST);
  if(licenceMeta?.schema!=='spfm-licence-manifest-v2'||licenceMeta.fairfaxOflIncluded!==true||!Array.isArray(licenceMeta.importedLicenceFiles)){
    throw Error('Font ZIP licence-manifest.json does not describe bundled Fairfax and imported licences.');
  }
  if(licenceMeta.importedLicenceFiles.length!==originalPaths.length || originalPaths.length>12){
    throw Error('Font ZIP original licence file count disagrees with its licence manifest.');
  }
  const expectedPaths=originalPathNames(licenceMeta.importedLicenceFiles);
  equalNames(originalPaths,expectedPaths,'original licence filename');
  const documents=[];
  for(let i=0;i<originalPaths.length;i++){
    const path=originalPaths[i],bytes=files.get(path),declared=licenceMeta.importedLicenceFiles[i];
    if(!declared||typeof declared.originalName!=='string'||!declared.originalName.trim()||
       !Number.isSafeInteger(declared.byteLength)||declared.byteLength!==bytes.length||
       bytes.length<1||bytes.length>MAX_DOC_BYTES){
      throw Error(`Font ZIP original licence ${path} does not match its manifest.`);
    }
    const name=path.slice('LICENSES/Original-'.length);
    const content=/\.pdf$/i.test(name)?'':new TextDecoder().decode(bytes);
    documents.push({name,originalName:declared.originalName,bytes,content,byteLength:bytes.length});
  }
  // Do not disguise this compiled ZIP as the historical, unmodified original
  // OTF. Its actual source is the emitted Ligatures TTF; the matching Literal
  // TTF is kept separately and used for future Literal compilation.
  return {
    ...pair,
    originalLicenceDocuments:documents,
    licenceMeta,
    sourceFontFilename:pair.manifest.fonts.ligatures,
    literalFontFilename:pair.manifest.fonts.literal,
    originalSourceName:typeof declaration?.originalSourceName==='string'
      ?declaration.originalSourceName:(typeof licenceMeta.sourceFile==='string'?licenceMeta.sourceFile:null),
  };
}
